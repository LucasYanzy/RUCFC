// Generates app/lib/polarLand.ts: the land mask behind the home page's route map.
//
// The map is a north-polar azimuthal equidistant projection -- the view from
// above the North Pole -- because that is where the shortest route between New
// Brunswick and Shanghai actually goes. It is turned so New Brunswick sits at
// the bottom and Shanghai near the top. The projected disc is cut into a square
// grid and each cell records whether its centre is on land.
//
// Run from the repository root:
//   npm install --no-save world-atlas@2 topojson-client@3 d3-geo@3
//   node scripts/generate-polar-land.mjs
// Land outlines are Natural Earth 1:110m (public domain) via world-atlas.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

// Keep these in step with the projection in app/components/RouteMap.tsx, which
// reads them from the generated file.
const LON_REF = -74.4474; // New Brunswick's longitude...
const THETA_REF = -90; // ...points straight down.
const COLAT_MAX = 74; // The rim of the disc is the 16th parallel north.
const GRID = 112; // Cells across the disc's diameter.

const bits = new Uint8Array(Math.ceil((GRID * GRID) / 8));
let landCells = 0;
for (let row = 0; row < GRID; row++) {
  for (let col = 0; col < GRID; col++) {
    const x = ((col + 0.5) / GRID) * 2 - 1;
    const y = 1 - ((row + 0.5) / GRID) * 2;
    const r = Math.hypot(x, y);
    if (r > 1) continue;
    const lat = 90 - r * COLAT_MAX;
    const theta = (Math.atan2(y, x) * 180) / Math.PI;
    let lon = LON_REF + (theta - THETA_REF);
    lon = ((((lon + 180) % 360) + 360) % 360) - 180;
    if (geoContains(land, [lon, lat])) {
      const i = row * GRID + col;
      bits[i >> 3] |= 1 << (i & 7);
      landCells++;
    }
  }
}

const out = `// Generated by scripts/generate-polar-land.mjs -- do not edit by hand.
// Land mask for the north-polar route map: ${GRID}x${GRID} cells, row-major from the
// top-left, one bit per cell (1 = land), little-endian within each byte, base64.
// ${landCells} land cells. Natural Earth 1:110m land, public domain.

export const POLAR = {
  lonRef: ${LON_REF},
  thetaRef: ${THETA_REF},
  colatMax: ${COLAT_MAX},
  grid: ${GRID},
} as const;

export const LAND_MASK =
  "${Buffer.from(bits).toString("base64")}";
`;

writeFileSync(new URL("../app/lib/polarLand.ts", import.meta.url), out);
console.log(`wrote app/lib/polarLand.ts: ${landCells} land cells`);
